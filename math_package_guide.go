// 5. СТЕПЕНИ И КОРНИ
// =============================================================================
func powerAndSqrtDemo() {
	fmt.Println("\n--- 5. СТЕПЕНИ И КОРНИ ---")

	// -------------------------------------------------------------------------
	// math.Pow(x, y float64) float64
	// -------------------------------------------------------------------------
	// Возвращает x в степени y (x^y, x**y).
	//
	// Особые случаи (основные):
	//   Pow(x, 0)    = 1      для любого x (включая NaN!)
	//   Pow(1, y)    = 1      для любого y
	//   Pow(x, 1)    = x
	//   Pow(x, 0.5)  = Sqrt(x) (квадратный корень)
	//   Pow(x, -1)   = 1/x
	//
	// Применение: сложные проценты, физика, математические формулы.
	fmt.Printf("Pow(2, 10)    = %.0f\n", math.Pow(2, 10))    // 1024
	fmt.Printf("Pow(3, 3)     = %.0f\n", math.Pow(3, 3))     // 27
	fmt.Printf("Pow(2, -1)    = %.2f\n", math.Pow(2, -1))    // 0.5
	fmt.Printf("Pow(4, 0.5)   = %.1f\n", math.Pow(4, 0.5))   // 2.0 (√4)
	fmt.Printf("Pow(27, 1/3.) = %.1f\n", math.Pow(27, 1.0/3)) // 3.0 (∛27)

	// -------------------------------------------------------------------------
	// math.Pow10(n int) float64
	// -------------------------------------------------------------------------
	// Возвращает 10 в степени n (10^n).
	// Быстрее, чем Pow(10, n) для целых степеней.
	//
	// Применение: конвертация единиц, научная нотация.
	fmt.Printf("Pow10(3)      = %.0f\n", math.Pow10(3))  // 1000
	fmt.Printf("Pow10(6)      = %.0f\n", math.Pow10(6))  // 1000000
	fmt.Printf("Pow10(-2)     = %.2f\n", math.Pow10(-2)) // 0.01

	// -------------------------------------------------------------------------
	// math.Sqrt(x float64) float64
	// -------------------------------------------------------------------------
	// Возвращает квадратный корень из x (√x).
	//
	// Особые случаи:
	//   Sqrt(+Inf)   = +Inf
	//   Sqrt(±0)     = ±0
	//   Sqrt(x < 0)  = NaN
	//   Sqrt(NaN)    = NaN
	//
	// Применение: теорема Пифагора, расстояния, стандартное отклонение.
	fmt.Printf("Sqrt(16)      = %.1f\n", math.Sqrt(16))     // 4.0
	fmt.Printf("Sqrt(2)       = %.6f\n", math.Sqrt(2))      // 1.414214
	fmt.Printf("Sqrt(0)       = %.1f\n", math.Sqrt(0))      // 0.0
	fmt.Printf("Sqrt(-1)      = %f\n", math.Sqrt(-1))       // NaN

	// -------------------------------------------------------------------------
	// math.Cbrt(x float64) float64
	// -------------------------------------------------------------------------
	// Возвращает кубический корень из x (∛x).
	// В отличие от Sqrt, работает и с отрицательными числами.
	//
	// Особые случаи:
	//   Cbrt(±0)   = ±0
	//   Cbrt(±Inf) = ±Inf
	//   Cbrt(NaN)  = NaN
	fmt.Printf("Cbrt(27)      = %.1f\n", math.Cbrt(27))     // 3.0
	fmt.Printf("Cbrt(-8)      = %.1f\n", math.Cbrt(-8))     // -2.0
	fmt.Printf("Cbrt(1000)    = %.1f\n", math.Cbrt(1000))   // 10.0

	// -------------------------------------------------------------------------
	// math.Hypot(p, q float64) float64
	// -------------------------------------------------------------------------
	// Возвращает √(p² + q²), т.е. длину гипотенузы прямоугольного
	// треугольника с катетами p и q.
	// Реализация защищена от переполнения (overflow/underflow).
	//
	// Применение: расстояние между точками, длина вектора.
	fmt.Printf("Hypot(3, 4)   = %.1f\n", math.Hypot(3, 4))   // 5.0
	fmt.Printf("Hypot(5, 12)  = %.1f\n", math.Hypot(5, 12))  // 13.0
}

