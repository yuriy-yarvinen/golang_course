func roundingDemo() {
	fmt.Println("\n--- 3. ОКРУГЛЕНИЕ ---")

	// -------------------------------------------------------------------------
	// math.Floor(x float64) float64
	// -------------------------------------------------------------------------
	// Округляет вниз (к минус бесконечности).
	// Возвращает наибольшее целое число, не превышающее x.
	//
	// Floor(2.7)  = 2.0   (округлили вниз)
	// Floor(-2.3) = -3.0  (вниз для отрицательных = дальше от нуля!)
	// Floor(5.0)  = 5.0   (уже целое)
	fmt.Printf("Floor(2.7)   = %.1f\n", math.Floor(2.7))   // 2.0
	fmt.Printf("Floor(-2.3)  = %.1f\n", math.Floor(-2.3))  // -3.0
	fmt.Printf("Floor(5.0)   = %.1f\n", math.Floor(5.0))   // 5.0

	// -------------------------------------------------------------------------
	// math.Ceil(x float64) float64
	// -------------------------------------------------------------------------
	// Округляет вверх (к плюс бесконечности).
	// Возвращает наименьшее целое число, не меньшее x.
	//
	// Ceil(2.1)  = 3.0   (округлили вверх)
	// Ceil(-2.7) = -2.0  (вверх для отрицательных = ближе к нулю!)
	fmt.Printf("Ceil(2.1)    = %.1f\n", math.Ceil(2.1))    // 3.0
	fmt.Printf("Ceil(-2.7)   = %.1f\n", math.Ceil(-2.7))   // -2.0
	fmt.Printf("Ceil(5.0)    = %.1f\n", math.Ceil(5.0))    // 5.0

	// -------------------------------------------------------------------------
	// math.Trunc(x float64) float64
	// -------------------------------------------------------------------------
	// Отбрасывает дробную часть (округляет к нулю).
	// Для положительных — как Floor, для отрицательных — как Ceil.
	//
	// Trunc(2.9)  = 2.0   (отбросили .9)
	// Trunc(-2.9) = -2.0  (отбросили .9, не -3!)
	fmt.Printf("Trunc(2.9)   = %.1f\n", math.Trunc(2.9))   // 2.0
	fmt.Printf("Trunc(-2.9)  = %.1f\n", math.Trunc(-2.9))  // -2.0

	// -------------------------------------------------------------------------
	// math.Round(x float64) float64
	// -------------------------------------------------------------------------
	// Округляет до ближайшего целого. При .5 округляет от нуля.
	// Это «обычное» математическое округление.
	//
	// Round(2.5)  = 3.0   (0.5 → вверх)
	// Round(-2.5) = -3.0  (0.5 → от нуля, т.е. вниз для отрицательных)
	// Round(2.4)  = 2.0
	fmt.Printf("Round(2.5)   = %.1f\n", math.Round(2.5))   // 3.0
	fmt.Printf("Round(2.4)   = %.1f\n", math.Round(2.4))   // 2.0
	fmt.Printf("Round(-2.5)  = %.1f\n", math.Round(-2.5))  // -3.0
	fmt.Printf("Round(-2.4)  = %.1f\n", math.Round(-2.4))  // -2.0

	// -------------------------------------------------------------------------
	// math.RoundToEven(x float64) float64
	// -------------------------------------------------------------------------
	// Округляет до ближайшего целого. При .5 округляет к чётному числу.
	// Также называется «банковское округление».
	// Применяется в финансах для уменьшения систематической ошибки.
	//
	// RoundToEven(2.5) = 2.0  (ближайшее чётное = 2)
	// RoundToEven(3.5) = 4.0  (ближайшее чётное = 4)
	// RoundToEven(4.5) = 4.0  (ближайшее чётное = 4)
	fmt.Printf("RoundToEven(2.5) = %.1f\n", math.RoundToEven(2.5)) // 2.0
	fmt.Printf("RoundToEven(3.5) = %.1f\n", math.RoundToEven(3.5)) // 4.0
	fmt.Printf("RoundToEven(4.5) = %.1f\n", math.RoundToEven(4.5)) // 4.0
	fmt.Printf("RoundToEven(2.3) = %.1f\n", math.RoundToEven(2.3)) // 2.0

	fmt.Println("\n  Совет: Округление до N знаков после запятой:")
	val := 3.14159
	rounded := math.Round(val*100) / 100
	fmt.Printf("  Round(3.14159 до 2 знаков) = %.2f\n", rounded) // 3.14
}

