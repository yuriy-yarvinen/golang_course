func absAndSignDemo() {
	fmt.Println("\n--- 2. МОДУЛЬ И ЗНАК ЧИСЛА ---")

	// -------------------------------------------------------------------------
	// math.Abs(x float64) float64
	// -------------------------------------------------------------------------
	// Возвращает абсолютное значение (модуль) числа x.
	// Если x >= 0, возвращает x. Если x < 0, возвращает -x.
	//
	// Особые случаи:
	//   Abs(±Inf) = +Inf
	//   Abs(NaN)  = NaN
	//
	// Применение: расчёт расстояний, погрешностей, нормализация значений.
	fmt.Printf("Abs(-7.5)   = %.1f\n", math.Abs(-7.5))   // 7.5
	fmt.Printf("Abs(3.2)    = %.1f\n", math.Abs(3.2))     // 3.2
	fmt.Printf("Abs(0)      = %.1f\n", math.Abs(0))       // 0.0
	fmt.Printf("Abs(-Inf)   = %f\n", math.Abs(math.Inf(-1))) // +Inf

	// -------------------------------------------------------------------------
	// math.Copysign(f, sign float64) float64
	// -------------------------------------------------------------------------
	// Возвращает значение с абсолютной величиной f и знаком sign.
	// Проще говоря: берёт модуль f и ставит ему знак от sign.
	//
	// Copysign(5, -1)  → -5 (модуль 5, знак от -1 = минус)
	// Copysign(-5, 1)  → 5  (модуль 5, знак от 1 = плюс)
	fmt.Printf("Copysign(5, -1)  = %.1f\n", math.Copysign(5, -1))  // -5.0
	fmt.Printf("Copysign(-5, 1)  = %.1f\n", math.Copysign(-5, 1))  // 5.0
	fmt.Printf("Copysign(-3, -7) = %.1f\n", math.Copysign(-3, -7)) // -3.0

	// -------------------------------------------------------------------------
	// math.Signbit(x float64) bool
	// -------------------------------------------------------------------------
	// Возвращает true, если x отрицательно или является отрицательным нулём.
	// Полезно для проверки знака числа, включая -0.
	fmt.Printf("Signbit(-5)  = %t\n", math.Signbit(-5))  // true
	fmt.Printf("Signbit(5)   = %t\n", math.Signbit(5))   // false
	fmt.Printf("Signbit(-0)  = %t\n", math.Signbit(math.Copysign(0, -1))) // true

	// -------------------------------------------------------------------------
	// math.Dim(x, y float64) float64
	// -------------------------------------------------------------------------
	// Возвращает max(x - y, 0). Если x > y, вернёт разницу.
	// Если x <= y, вернёт 0. Иногда называется "positive difference".
	//
	// Применение: ограничение значений снизу нулём, расчёт превышений.
	fmt.Printf("Dim(7, 3)  = %.1f\n", math.Dim(7, 3))  // 4.0
	fmt.Printf("Dim(3, 7)  = %.1f\n", math.Dim(3, 7))  // 0.0
	fmt.Printf("Dim(5, 5)  = %.1f\n", math.Dim(5, 5))  // 0.0
}

