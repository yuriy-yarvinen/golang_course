// 11. РАЗБОР ЧИСЛА НА ЧАСТИ (Float Decomposition)
// =============================================================================
func floatPartsDemo() {
	fmt.Println("\n--- 11. РАЗБОР ЧИСЛА НА ЧАСТИ ---")

	// -------------------------------------------------------------------------
	// math.Modf(f float64) (int float64, frac float64)
	// -------------------------------------------------------------------------
	// Разбивает число на целую и дробную части.
	// Обе части имеют тот же знак, что и f.
	//
	// Modf(3.75)  → (3.0, 0.75)
	// Modf(-2.5)  → (-2.0, -0.5)
	intPart, fracPart := math.Modf(3.75)
	fmt.Printf("Modf(3.75)   = int=%.1f, frac=%.2f\n", intPart, fracPart)
	intPart, fracPart = math.Modf(-2.5)
	fmt.Printf("Modf(-2.5)   = int=%.1f, frac=%.2f\n", intPart, fracPart)

	// -------------------------------------------------------------------------
	// math.Frexp(f float64) (frac float64, exp int)
	// -------------------------------------------------------------------------
	// Разбивает f на нормализованную мантиссу и двоичную экспоненту:
	// f = frac × 2^exp, где 0.5 <= |frac| < 1.
	//
	// Применение: работа с представлением чисел с плавающей точкой.
	frac, exp := math.Frexp(8.0)
	fmt.Printf("Frexp(8)     = frac=%.1f, exp=%d  (%.1f × 2^%d = 8)\n", frac, exp, frac, exp)
	frac, exp = math.Frexp(0.5)
	fmt.Printf("Frexp(0.5)   = frac=%.1f, exp=%d  (%.1f × 2^%d = 0.5)\n", frac, exp, frac, exp)

	// -------------------------------------------------------------------------
	// math.Ldexp(frac float64, exp int) float64
	// -------------------------------------------------------------------------
	// Обратная к Frexp: возвращает frac × 2^exp.
	// Ldexp(Frexp(x)) = x
	fmt.Printf("Ldexp(0.5, 4) = %.1f\n", math.Ldexp(0.5, 4)) // 8.0 (0.5 × 2⁴)
	fmt.Printf("Ldexp(1, 10)  = %.0f\n", math.Ldexp(1, 10))   // 1024 (1 × 2¹⁰)

	// -------------------------------------------------------------------------
	// math.Float64bits(f float64) uint64
	// -------------------------------------------------------------------------
	// Возвращает IEEE 754 двоичное представление float64 как uint64.
	// Не выполняет преобразование — просто интерпретирует те же биты.
	//
	// Применение: низкоуровневая работа с битами float, хеширование.
	bits := math.Float64bits(1.0)
	fmt.Printf("Float64bits(1.0) = %064b\n", bits)

	// -------------------------------------------------------------------------
	// math.Float64frombits(b uint64) float64
	// -------------------------------------------------------------------------
	// Обратная к Float64bits: интерпретирует uint64 как float64.
	val := math.Float64frombits(bits)
	fmt.Printf("Float64frombits  = %.1f\n", val) // 1.0

	// -------------------------------------------------------------------------
	// math.Float32bits(f float32) uint32
	// math.Float32frombits(b uint32) float32
	// -------------------------------------------------------------------------
	// Аналогичные функции для float32.
	bits32 := math.Float32bits(1.0)
	fmt.Printf("Float32bits(1.0) = %032b\n", bits32)
}

