// 6. ЭКСПОНЕНТЫ И ЛОГАРИФМЫ
// =============================================================================
func expAndLogDemo() {
	fmt.Println("\n--- 6. ЭКСПОНЕНТЫ И ЛОГАРИФМЫ ---")

	// -------------------------------------------------------------------------
	// math.Exp(x float64) float64
	// -------------------------------------------------------------------------
	// Возвращает e^x (e в степени x), где e ≈ 2.71828...
	// Это экспоненциальная функция — обратная к натуральному логарифму.
	//
	// Особые случаи:
	//   Exp(+Inf) = +Inf
	//   Exp(NaN)  = NaN
	//
	// Применение: рост популяции, радиоактивный распад, финансы.
	fmt.Printf("Exp(0)       = %.1f\n", math.Exp(0))       // 1.0 (e^0 = 1)
	fmt.Printf("Exp(1)       = %.6f\n", math.Exp(1))       // 2.718282 (e^1 = e)
	fmt.Printf("Exp(2)       = %.6f\n", math.Exp(2))       // 7.389056
	fmt.Printf("Exp(-1)      = %.6f\n", math.Exp(-1))      // 0.367879 (1/e)

	// -------------------------------------------------------------------------
	// math.Exp2(x float64) float64
	// -------------------------------------------------------------------------
	// Возвращает 2^x (2 в степени x).
	// Более точная и быстрая, чем Pow(2, x).
	//
	// Применение: размеры буферов, информатика (биты).
	fmt.Printf("Exp2(10)     = %.0f\n", math.Exp2(10))     // 1024
	fmt.Printf("Exp2(0)      = %.0f\n", math.Exp2(0))      // 1
	fmt.Printf("Exp2(0.5)    = %.6f\n", math.Exp2(0.5))    // 1.414214 (√2)

	// -------------------------------------------------------------------------
	// math.Expm1(x float64) float64
	// -------------------------------------------------------------------------
	// Возвращает e^x - 1. Точнее, чем Exp(x) - 1 при малых x.
	// Когда x близок к 0, Exp(x) ≈ 1, и вычитание 1 теряет точность.
	// Expm1 решает эту проблему.
	//
	// Применение: финансовые расчёты с малыми процентными ставками.
	fmt.Printf("Expm1(0)     = %.1f\n", math.Expm1(0))     // 0.0
	fmt.Printf("Expm1(1e-10) = %.15e\n", math.Expm1(1e-10)) // точный результат
	fmt.Printf("Exp(1e-10)-1 = %.15e\n", math.Exp(1e-10)-1) // потеря точности!

	fmt.Println()

	// -------------------------------------------------------------------------
	// math.Log(x float64) float64
	// -------------------------------------------------------------------------
	// Натуральный логарифм (ln x, логарифм по основанию e).
	// Обратная функция к Exp: Log(Exp(x)) = x.
	//
	// Особые случаи:
	//   Log(+Inf) = +Inf
	//   Log(0)    = -Inf
	//   Log(x<0)  = NaN
	//   Log(NaN)  = NaN
	//
	// Применение: информатика, термодинамика, акустика (децибелы).
	fmt.Printf("Log(1)       = %.1f\n", math.Log(1))       // 0.0 (ln(1) = 0)
	fmt.Printf("Log(e)       = %.1f\n", math.Log(math.E))  // 1.0 (ln(e) = 1)
	fmt.Printf("Log(10)      = %.6f\n", math.Log(10))      // 2.302585

	// -------------------------------------------------------------------------
	// math.Log2(x float64) float64
	// -------------------------------------------------------------------------
	// Логарифм по основанию 2 (log₂ x).
	// Сколько раз нужно умножить 2, чтобы получить x.
	//
	// Применение: сложность алгоритмов (O(log n)), количество бит.
	fmt.Printf("Log2(1)      = %.1f\n", math.Log2(1))      // 0.0
	fmt.Printf("Log2(8)      = %.1f\n", math.Log2(8))      // 3.0 (2³ = 8)
	fmt.Printf("Log2(1024)   = %.1f\n", math.Log2(1024))   // 10.0

	// -------------------------------------------------------------------------
	// math.Log10(x float64) float64
	// -------------------------------------------------------------------------
	// Десятичный логарифм (lg x, log₁₀ x).
	// Количество цифр числа примерно равно Floor(Log10(x)) + 1.
	//
	// Применение: децибелы, шкала Рихтера, pH.
	fmt.Printf("Log10(1)     = %.1f\n", math.Log10(1))     // 0.0
	fmt.Printf("Log10(100)   = %.1f\n", math.Log10(100))   // 2.0
	fmt.Printf("Log10(1000)  = %.1f\n", math.Log10(1000))  // 3.0

	// -------------------------------------------------------------------------
	// math.Log1p(x float64) float64
	// -------------------------------------------------------------------------
	// Возвращает ln(1 + x). Точнее, чем Log(1 + x) при малых x.
	// Аналогично Expm1, решает проблему потери точности.
	//
	// Применение: финансовые расчёты, статистика.
	fmt.Printf("Log1p(0)     = %.1f\n", math.Log1p(0))     // 0.0
	fmt.Printf("Log1p(1e-15) = %.15e\n", math.Log1p(1e-15))

	// -------------------------------------------------------------------------
	// math.Logb(x float64) float64
	// -------------------------------------------------------------------------
	// Возвращает двоичный порядок (экспоненту) числа x.
	// Это по сути Floor(Log2(Abs(x))), но точнее.
	fmt.Printf("Logb(8)      = %.1f\n", math.Logb(8))      // 3.0
	fmt.Printf("Logb(100)    = %.1f\n", math.Logb(100))    // 6.0

	// -------------------------------------------------------------------------
	// math.Ilogb(x float64) int
	// -------------------------------------------------------------------------
	// Как Logb, но возвращает int.
	fmt.Printf("Ilogb(8)     = %d\n", math.Ilogb(8))      // 3
	fmt.Printf("Ilogb(100)   = %d\n", math.Ilogb(100))    // 6
}

