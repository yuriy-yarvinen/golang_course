// 10. ОСТАТОК ОТ ДЕЛЕНИЯ
// =============================================================================
func remainderAndModDemo() {
	fmt.Println("\n--- 10. ОСТАТОК ОТ ДЕЛЕНИЯ ---")

	// -------------------------------------------------------------------------
	// math.Mod(x, y float64) float64
	// -------------------------------------------------------------------------
	// Возвращает остаток от деления x на y (truncated division).
	// Результат: x - Trunc(x/y) * y
	// Знак результата совпадает со знаком x.
	//
	// Mod(7, 3)    = 1   (7 = 2*3 + 1)
	// Mod(-7, 3)   = -1  (знак как у -7)
	// Mod(7, -3)   = 1   (знак как у 7)
	// Mod(5.5, 2)  = 1.5
	fmt.Printf("Mod(7, 3)     = %.1f\n", math.Mod(7, 3))     // 1.0
	fmt.Printf("Mod(-7, 3)    = %.1f\n", math.Mod(-7, 3))    // -1.0
	fmt.Printf("Mod(7, -3)    = %.1f\n", math.Mod(7, -3))    // 1.0
	fmt.Printf("Mod(5.5, 2)   = %.1f\n", math.Mod(5.5, 2))   // 1.5

	// -------------------------------------------------------------------------
	// math.Remainder(x, y float64) float64
	// -------------------------------------------------------------------------
	// IEEE 754 остаток от деления. Отличие от Mod:
	// Результат: x - Round(x/y) * y (Round, а не Trunc!)
	// Результат может быть отрицательным даже если оба аргумента положительны.
	// Результат всегда в диапазоне [-y/2, y/2].
	//
	// Remainder(7, 3)  = 1    (7/3 ≈ 2.33, Round = 2, 7 - 2*3 = 1)
	// Remainder(8, 3)  = -1   (8/3 ≈ 2.67, Round = 3, 8 - 3*3 = -1)
	fmt.Printf("Remainder(7, 3)  = %.1f\n", math.Remainder(7, 3))  // 1.0
	fmt.Printf("Remainder(8, 3)  = %.1f\n", math.Remainder(8, 3))  // -1.0
	fmt.Printf("Remainder(5, 3)  = %.1f\n", math.Remainder(5, 3))  // -1.0

	// -------------------------------------------------------------------------
	// math.FMA(x, y, z float64) float64
	// -------------------------------------------------------------------------
	// Fused Multiply-Add: вычисляет x*y + z за одну операцию.
	// Точнее, чем раздельное вычисление x*y + z, т.к. промежуточный
	// результат x*y не округляется.
	//
	// Применение: линейная алгебра, графика, научные вычисления.
	fmt.Printf("FMA(2, 3, 4)  = %.1f\n", math.FMA(2, 3, 4)) // 10.0 (2*3 + 4)
}

