func minMaxDemo() {
	fmt.Println("\n--- 4. МИНИМУМ И МАКСИМУМ ---")

	// -------------------------------------------------------------------------
	// math.Min(x, y float64) float64
	// -------------------------------------------------------------------------
	// Возвращает меньшее из двух чисел.
	//
	// Особые случаи:
	//   Min(x, -Inf) = Min(-Inf, x) = -Inf
	//   Min(x, NaN)  = Min(NaN, x)  = NaN
	//   Min(+0, ±0)  = Min(±0, +0)  = +0
	//   Min(-0, -0)  = -0
	fmt.Printf("Min(3, 7)     = %.1f\n", math.Min(3, 7))     // 3.0
	fmt.Printf("Min(-5, -2)   = %.1f\n", math.Min(-5, -2))   // -5.0

	// -------------------------------------------------------------------------
	// math.Max(x, y float64) float64
	// -------------------------------------------------------------------------
	// Возвращает большее из двух чисел.
	//
	// Особые случаи:
	//   Max(x, +Inf) = Max(+Inf, x) = +Inf
	//   Max(x, NaN)  = Max(NaN, x)  = NaN
	//   Max(+0, ±0)  = Max(±0, +0)  = +0
	//   Max(-0, -0)  = -0
	fmt.Printf("Max(3, 7)     = %.1f\n", math.Max(3, 7))     // 7.0
	fmt.Printf("Max(-5, -2)   = %.1f\n", math.Max(-5, -2))   // -2.0

	fmt.Println("\n  Совет: Для min/max из нескольких чисел используйте цепочку:")
	a, b, c := 5.0, 2.0, 8.0
	minVal := math.Min(a, math.Min(b, c))
	maxVal := math.Max(a, math.Max(b, c))
	fmt.Printf("  Min(5, 2, 8) = %.1f\n", minVal) // 2.0
	fmt.Printf("  Max(5, 2, 8) = %.1f\n", maxVal) // 8.0

	fmt.Println("  Начиная с Go 1.21, для целых чисел есть встроенные min() и max().")
}

