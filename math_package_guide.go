// 12. СПЕЦИАЛЬНЫЕ ЗНАЧЕНИЯ (Inf, NaN)
// =============================================================================
func specialValuesDemo() {
	fmt.Println("\n--- 12. СПЕЦИАЛЬНЫЕ ЗНАЧЕНИЯ ---")

	// -------------------------------------------------------------------------
	// math.Inf(sign int) float64
	// -------------------------------------------------------------------------
	// Возвращает положительную бесконечность (sign >= 0) или
	// отрицательную бесконечность (sign < 0).
	//
	// +Inf больше любого конечного числа.
	// -Inf меньше любого конечного числа.
	fmt.Printf("Inf(1)       = %f\n", math.Inf(1))   // +Inf
	fmt.Printf("Inf(-1)      = %f\n", math.Inf(-1))  // -Inf

	// -------------------------------------------------------------------------
	// math.IsInf(f float64, sign int) bool
	// -------------------------------------------------------------------------
	// Проверяет, является ли f бесконечностью.
	// sign > 0:  проверяет +Inf
	// sign < 0:  проверяет -Inf
	// sign == 0: проверяет любую бесконечность (±Inf)
	fmt.Printf("IsInf(+Inf, 1)  = %t\n", math.IsInf(math.Inf(1), 1))  // true
	fmt.Printf("IsInf(+Inf, -1) = %t\n", math.IsInf(math.Inf(1), -1)) // false
	fmt.Printf("IsInf(5, 0)     = %t\n", math.IsInf(5, 0))            // false

	// -------------------------------------------------------------------------
	// math.NaN() float64
	// -------------------------------------------------------------------------
	// Возвращает значение "Not-a-Number" (не число).
	// NaN получается при невалидных операциях: 0/0, Sqrt(-1), Log(-1).
	//
	// Главная особенность NaN:
	//   NaN != NaN  (NaN не равен ничему, даже самому себе!)
	//   Любая арифметика с NaN даёт NaN.
	nan := math.NaN()
	fmt.Printf("NaN          = %f\n", nan)
	fmt.Printf("NaN == NaN   = %t\n", nan == nan)         // false!
	fmt.Printf("NaN + 5      = %f\n", nan+5)              // NaN
	fmt.Printf("NaN > 0      = %t\n", nan > 0)            // false
	fmt.Printf("NaN < 0      = %t\n", nan < 0)            // false

	// -------------------------------------------------------------------------
	// math.IsNaN(f float64) bool
	// -------------------------------------------------------------------------
	// Единственный надёжный способ проверить NaN (т.к. NaN != NaN).
	fmt.Printf("IsNaN(NaN)   = %t\n", math.IsNaN(nan))    // true
	fmt.Printf("IsNaN(5)     = %t\n", math.IsNaN(5))      // false
	fmt.Printf("IsNaN(Inf)   = %t\n", math.IsNaN(math.Inf(1))) // false
}

